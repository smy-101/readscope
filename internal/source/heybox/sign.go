package heybox

// sign.go — the hkey request signature, both variants the smoke
// told apart (smoke.md 关键发现 1): variant A pairs with version
// 999.0.3 (RSSHub / heybox-cli lineage — readscope's default), B
// with 999.0.4 (the current web client). The server rejects crossed
// pairs with 非法请求, so a version switch MUST swap the signer with
// the version string — that binding is clientShape below, the single
// seam the stop-loss ladder turns.
//
// Both variants sign the canonical path only ("/" + the path's own
// slash-joined segments + "/"); query parameters ride unsigned. The
// signature triple rides as the query parameters hkey/_time/nonce.
//
// Reference vectors pinning every line of this file live in
// sign_test.go — generated by running the ORIGINAL JavaScript
// implementations (RSSHub util.ts, WenfuRainbow signature.ts) on
// fixed inputs during the smoke (refs/gen.mjs), so a mistranscribed
// constant or an upstream algorithm change goes red immediately.

import (
	"crypto/md5" // #nosec G501 -- required by the upstream request-signing protocol.
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"strconv"
	"strings"
	"time"
	"unicode"
)

// clientShape binds the version query parameter to the signature
// variant the server expects behind it (the smoke's cross matrix:
// A+999.0.4 and B+999.0.3 both answer 非法请求). Swapping one without
// the other is a guaranteed break, so they travel as a pair.
type clientShape struct {
	version string
	sign    func(path string, ts int64, nonce string) string
}

// shapeWebV3 is the default: variant A on 999.0.3, the RSSHub /
// heybox-cli lineage — the most-referenced implementation family and
// the one the whole smoke matrix ran green on.
var shapeWebV3 = clientShape{version: "999.0.3", sign: signA}

// shapeWebV4 is the reserved switch: variant B on 999.0.4, the
// current web client's own pair. When heybox bumps the version gate
// ("版本过低"-style refusals), flipping the transport onto this shape
// is the one-line first rung of the stop-loss ladder.
var shapeWebV4 = clientShape{version: "999.0.4", sign: signB}

// alphabetA is variant A's 24-character encoding table (RSSHub
// util.ts / heybox-cli signer.go, verbatim).
const alphabetA = "JKMNPQRTX1234OABCDFG56789H"

// signA is the variant A signature (999.0.3 family). The name spell
// out the GF(2⁸) ladder the checksum mixes through — z/j/aa/o are
// the original implementation's own names, kept so the code diffs
// against its sources line for line.
func signA(path string, ts int64, nonce string) string {
	canonical := canonicalPath(path)
	seed := md5Hex(onlyDigits(nonce + alphabetA))
	digits := onlyDigits(md5Hex(fmt.Sprintf("%d%s%s", ts+1, canonical, seed)))
	if len(digits) > 9 {
		digits = digits[:9]
	}
	for len(digits) < 9 {
		digits += "0"
	}
	var n int64
	for _, r := range digits {
		n = n*10 + int64(r-'0')
	}
	enc := make([]byte, 0, 5)
	base := int64(len(alphabetA))
	for range 5 {
		enc = append(enc, alphabetA[n%base])
		n /= base
	}
	a, b, c, d := enc[1], enc[2], enc[3], enc[4] // the last 4 bytes
	mixed := [4]byte{
		oA(a) ^ aaA(b) ^ jA(c) ^ zA(d),
		zA(a) ^ oA(b) ^ aaA(c) ^ jA(d),
		jA(a) ^ zA(b) ^ oA(c) ^ aaA(d),
		aaA(a) ^ jA(b) ^ zA(c) ^ oA(d),
	}
	return string(enc) + fmt.Sprintf("%02d", (int(mixed[0])+int(mixed[1])+int(mixed[2])+int(mixed[3]))%100)
}

func zA(v byte) byte  { return xtime(v) ^ v }
func jA(v byte) byte  { return zA(xtime(v)) }
func aaA(v byte) byte { return jA(zA(xtime(v))) }
func oA(v byte) byte  { return aaA(v) ^ jA(v) ^ zA(v) }

// alphabetB is variant B's table (WenfuRainbow signature.ts,
// verbatim — note it is NOT a permutation of A's).
const alphabetB = "AB45STUVWZEFGJ6CH01D237IXYPQRKLMN89"

// signB is the variant B signature (999.0.4 family): the three
// encoded inputs interleaved, truncated to 20 chars, MD5'd, then a
// mixed-checksum tail. avB's negative offset takes the alphabet's
// tail per the original JS slice semantics.
func signB(path string, ts int64, nonce string) string {
	canonical := canonicalPath(path)
	il := interleave([]string{
		avB(strconv.FormatInt(ts+1, 10), -2),
		svB(canonical),
		svB(nonce),
	})
	if len(il) > 20 {
		il = il[:20]
	}
	hash := md5Hex(il)
	last6 := kmB([]byte(hash[len(hash)-6:]))
	sum := 0
	for _, v := range last6 {
		sum += int(v)
	}
	return avB(hash[:5], -4) + fmt.Sprintf("%02d", sum%100)
}

func vmB(e byte) byte { return xtime(e) }
func qmB(e byte) byte { return vmB(e) ^ e }
func dmB(e byte) byte { return qmB(vmB(e)) }
func ymB(e byte) byte { return dmB(qmB(vmB(e))) }
func gmB(e byte) byte { return ymB(e) ^ dmB(e) ^ qmB(e) }

// avB encodes text through the alphabet after dropping the leading
// offset characters (negative: the tail), the JS slice semantics of
// the original's av().
func avB(text string, offset int) string {
	alpha := alphabetB
	if offset < 0 {
		alpha = alpha[:len(alpha)+offset]
	}
	var b strings.Builder
	for _, r := range text {
		b.WriteByte(alpha[int(r)%len(alpha)])
	}
	return b.String()
}

// svB encodes text through the full alphabet (the original's sv()).
func svB(text string) string {
	var b strings.Builder
	for _, r := range text {
		b.WriteByte(alphabetB[int(r)%len(alphabetB)])
	}
	return b.String()
}

// interleave round-robins the inputs' bytes (the original's
// interleave()).
func interleave(arr []string) string {
	max := 0
	for _, s := range arr {
		if len(s) > max {
			max = len(s)
		}
	}
	var b strings.Builder
	for i := 0; i < max; i++ {
		for _, s := range arr {
			if i < len(s) {
				b.WriteByte(s[i])
			}
		}
	}
	return b.String()
}

// kmB mixes four bytes through the GF(2⁸) ladder in place (the
// original's km()).
func kmB(e []byte) []byte {
	t := [4]byte{
		gmB(e[0]) ^ ymB(e[1]) ^ dmB(e[2]) ^ qmB(e[3]),
		qmB(e[0]) ^ gmB(e[1]) ^ ymB(e[2]) ^ dmB(e[3]),
		dmB(e[0]) ^ qmB(e[1]) ^ gmB(e[2]) ^ ymB(e[3]),
		ymB(e[0]) ^ dmB(e[1]) ^ qmB(e[2]) ^ gmB(e[3]),
	}
	copy(e, t[:])
	return e
}

// canonicalPath normalizes the endpoint path into the form both
// variants sign: slash-split, re-joined, wrapped in slashes — double
// slashes and trailing quirks collapse away.
func canonicalPath(path string) string {
	return "/" + strings.Join(strings.FieldsFunc(path, func(r rune) bool { return r == '/' }), "/") + "/"
}

// xtime is the GF(2⁸) doubling both variants' ladders ride (the
// original's _0x… helpers, renamed after AES's xtime).
func xtime(v byte) byte {
	if v&128 != 0 {
		return byte((int(v)<<1 ^ 27) & 255)
	}
	return v << 1
}

// md5Hex is the protocol's digest — compatibility, not security.
func md5Hex(value string) string {
	sum := md5.Sum([]byte(value)) // #nosec G401 -- protocol compatibility, not password hashing.
	return hex.EncodeToString(sum[:])
}

// onlyDigits keeps the ASCII digits of a digest — both variants seed
// from the digit subsequence, not the hex string itself.
func onlyDigits(value string) string {
	var out strings.Builder
	for _, r := range value {
		if unicode.IsDigit(r) {
			out.WriteRune(r)
		}
	}
	return out.String()
}

// newNonce mints one request's nonce: uppercase MD5 over the
// timestamp and 16 fresh random bytes (both reference families'
// recipe). Fresh randomness per request is part of the protocol; the
// reference vectors pin the signature given a fixed nonce, not the
// nonce itself.
func newNonce(ts int64) (string, error) {
	random := make([]byte, 16)
	if _, err := rand.Read(random); err != nil {
		return "", fmt.Errorf("heybox nonce: %w", err)
	}
	return strings.ToUpper(md5Hex(fmt.Sprintf("%d%s", ts, hex.EncodeToString(random)))), nil
}

// signTriple signs one request: the hkey plus the _time/nonce that
// made it. Variant A's pair (the transport's default shape).
func signTriple(shape clientShape, path string, now time.Time) (hkey, nonce string, ts int64, err error) {
	ts = now.Unix()
	nonce, err = newNonce(ts)
	if err != nil {
		return "", "", 0, err
	}
	return shape.sign(path, ts, nonce), nonce, ts, nil
}
